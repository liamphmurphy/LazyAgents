import json,re,sys
import os; sys.path.insert(0,os.path.dirname(os.path.abspath(__file__)))
import lib, shell, screens
from lib import F
# Every screen is self-contained: the review preview doesn't follow component
# references nested inside an added frame, so instances would preview empty.
X0=3200  # right of the earlier, superseded suggestions
frames=[]
for i,fn in enumerate(screens.ORDER):
    fr=fn(X0+(i%2)*1560,(i//2)*1020).node
    frames.append(fr)
def num(v):
    if isinstance(v,float):
        v=round(v,1); return int(v) if v==int(v) else v
    return v
def compact(n):
    if n.get('name','').startswith('icon'):
        n.pop('name'); n.pop('join',None)
    if 'd' in n: n['d']=re.sub(r'-?\d+\.\d+',lambda m:('%g'%round(float(m.group()),1)),n['d'])
    for k in list(n): n[k]=num(n[k])
    for p in n.get('paragraphs',[]):
        for r in p['runs']:
            for k in r: r[k]=num(r[k])
    for c in n.get('children',[]): compact(c)
for n in frames: compact(n)
# frame ids for review clarity
for i,fr in enumerate(frames):
    fr["id"]=f"n_kv3_{i:02d}"
ops=[{"op":"add_node","parent":"p_b63ucjzq7w","why":"Knowledge redesign: "+fr["name"].split(" · ",1)[1],"node":fr} for fr in frames]
out=os.path.join(os.path.dirname(os.path.abspath(__file__)),"..","..","interface-mockups.json")
json.dump({"design":"01a1d27a-eb95-78f4-a49c-2d71a04b7be5","page":"p_b63ucjzq7w","note":"Design ops for the Knowledge interface mockups (LAZYAGENTS-186), as proposed to the design. Generated by mockups/src/build.py; regenerate rather than hand-edit.","ops":ops},open(out,"w"),indent=1,ensure_ascii=False)
