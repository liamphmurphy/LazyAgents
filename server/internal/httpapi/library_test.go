// A generated image is in its owner's Library, outlives its chat (the
// attachment sweep keeps the shared object), and its object goes only when
// nothing holds it any more.
func TestLibraryKeepsGeneratedImages(t *testing.T) {
	e, s3 := newAvatarEnv(t)
	chat := e.newChat(nil)
	chatID := uuid.MustParse(chat["id"].(string))
	ctx := t.Context()
	reply, err := e.q.AppendChatMessage(ctx, store.AppendChatMessageParams{SessionID: chatID, Role: "assistant", BodyMd: "here", ContextRefs: []byte("[]"), Citations: []byte("[]")})
	if err != nil {
		t.Fatal(err)
	}
	png := []byte("\x89PNG\r\n\x1a\nbytes")
	key := "chat-attachments/" + uuid.NewString()
	s3.put(avatarBucket+"/"+key, png, "image/png")
	if _, err := e.q.CreateGeneratedChatAttachment(ctx, store.CreateGeneratedChatAttachmentParams{WorkspaceID: e.me.WorkspaceID, UserID: e.me.ID, MessageID: &reply.ID,
		Filename: "cat.png", ContentType: "image/png", SizeBytes: int64(len(png)), BlobKey: key}); err != nil {
		t.Fatal(err)
	}
	if _, err := e.q.CreateLibraryItem(ctx, store.CreateLibraryItemParams{WorkspaceID: e.me.WorkspaceID, UserID: e.me.ID, Kind: "image", Title: "Cats",
		Filename: "cat.png", ContentType: "image/png", SizeBytes: int64(len(png)), BlobKey: key, ChatID: &chatID, MessageID: &reply.ID}); err != nil {
		t.Fatal(err)
	}
	// The quota counts the shared object once.
	if n, err := e.q.ChatGeneratedImageBytes(ctx, store.ChatGeneratedImageBytesParams{WorkspaceID: e.me.WorkspaceID, UserID: e.me.ID}); err != nil || n != int64(len(png)) {
		t.Fatalf("generated bytes %d %v", n, err)
	}

	items := e.want("GET", "/library?kind=image", nil, 200)["items"].([]any)
	if len(items) != 1 {
		t.Fatalf("items %v", items)
	}
	it := items[0].(map[string]any)
	if it["title"] != "Cats" || it["kind"] != "image" || it["chat_id"] != chatID.String() || it["project_key"] == nil {
		t.Fatalf("item %v", it)
	}
	id := it["id"].(string)
	res, err := http.Get(e.srv.URL + "/api/v1/library/" + id + "/content")
	if err != nil {
		t.Fatal(err)
	}
	body, _ := io.ReadAll(res.Body)
	res.Body.Close()
	if res.StatusCode != 200 || string(body) != string(png) || res.Header.Get("Content-Type") != "image/png" {
		t.Fatalf("content %d %q %s", res.StatusCode, body, res.Header.Get("Content-Type"))
	}

	// Someone else sees nothing and can't delete it.
	other, err := e.q.CreateUser(ctx, store.CreateUserParams{WorkspaceID: e.me.WorkspaceID, Name: "Other", Email: "o@example.com", Initials: "OT"})
	if err != nil {
		t.Fatal(err)
	}
	if rows, err := e.q.ListLibraryItems(ctx, store.ListLibraryItemsParams{WorkspaceID: e.me.WorkspaceID, UserID: other.ID, RowLimit: 10}); err != nil || len(rows) != 0 {
		t.Fatalf("other's library %v %v", rows, err)
	}
	if _, err := e.q.DeleteLibraryItem(ctx, store.DeleteLibraryItemParams{ID: uuid.MustParse(id), WorkspaceID: e.me.WorkspaceID, UserID: other.ID}); err == nil {
		t.Fatal("another user deleted the item")
	}

	// Deleting the chat detaches the attachment; the sweep drops its row but
	// not the object the Library still uses.
	e.want("DELETE", "/chats/"+chatID.String(), nil, http.StatusNoContent)
	swept, err := e.q.DeleteStaleChatAttachments(ctx, store.DeleteStaleChatAttachmentsParams{Cutoff: time.Now().Add(time.Hour), RowLimit: 1000})
	if err != nil {
		t.Fatal(err)
	}
	for _, k := range swept {
		if k == key {
			t.Fatal("sweep returned a key the Library holds")
		}
	}
	items = e.want("GET", "/library", nil, 200)["items"].([]any)
	if len(items) != 1 || items[0].(map[string]any)["chat_id"] != nil {
		t.Fatalf("after chat delete %v", items)
	}
	if n, err := e.q.ChatGeneratedImageBytes(ctx, store.ChatGeneratedImageBytesParams{WorkspaceID: e.me.WorkspaceID, UserID: e.me.ID}); err != nil || n != int64(len(png)) {
		t.Fatalf("library images still count toward the cap: %d %v", n, err)
	}

	// Removing it from the Library now removes the object too.
	e.want("DELETE", "/library/"+id, nil, http.StatusNoContent)
	if keys := s3.keys(avatarBucket + "/" + key); len(keys) != 0 {
		t.Fatalf("object kept %v", keys)
	}
	e.want("DELETE", "/library/"+id, nil, http.StatusNotFound)
	e.want("GET", "/library/"+id+"/content", nil, http.StatusNotFound)
}

// While its chat still shows the image, removing it from the Library keeps
// the object.
func TestLibraryDeleteKeepsChatImage(t *testing.T) {
	e, s3 := newAvatarEnv(t)
	chat := e.newChat(nil)
	chatID := uuid.MustParse(chat["id"].(string))
	ctx := t.Context()
	reply, err := e.q.AppendChatMessage(ctx, store.AppendChatMessageParams{SessionID: chatID, Role: "assistant", BodyMd: "here", ContextRefs: []byte("[]"), Citations: []byte("[]")})
	if err != nil {
		t.Fatal(err)
	}
	png := []byte("\x89PNG\r\n\x1a\nbytes")
	key := "chat-attachments/" + uuid.NewString()
	s3.put(avatarBucket+"/"+key, png, "image/png")
	if _, err := e.q.CreateGeneratedChatAttachment(ctx, store.CreateGeneratedChatAttachmentParams{WorkspaceID: e.me.WorkspaceID, UserID: e.me.ID, MessageID: &reply.ID,
		Filename: "cat.png", ContentType: "image/png", SizeBytes: int64(len(png)), BlobKey: key}); err != nil {
		t.Fatal(err)
	}
	item, err := e.q.CreateLibraryItem(ctx, store.CreateLibraryItemParams{WorkspaceID: e.me.WorkspaceID, UserID: e.me.ID, Kind: "image", Title: "Cats",
		Filename: "cat.png", ContentType: "image/png", SizeBytes: int64(len(png)), BlobKey: key, ChatID: &chatID, MessageID: &reply.ID})
	if err != nil {
		t.Fatal(err)
	}
	e.want("DELETE", "/library/"+item.ID.String(), nil, http.StatusNoContent)
	if keys := s3.keys(avatarBucket + "/" + key); len(keys) != 1 {
		t.Fatalf("chat image object removed: %v", keys)
	}
}

// A diagram is saved only on request, once per content, and only from the
// caller's own assistant replies.
func TestLibrarySavesDiagrams(t *testing.T) {
	e, s3 := newAvatarEnv(t)
	chat := e.newChat(nil)
	chatID := uuid.MustParse(chat["id"].(string))
	ctx := t.Context()
	reply, err := e.q.AppendChatMessage(ctx, store.AppendChatMessageParams{SessionID: chatID, Role: "assistant", BodyMd: "here", ContextRefs: []byte("[]"), Citations: []byte("[]")})
	if err != nil {
		t.Fatal(err)
	}
	const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 4 2"><rect width="4" height="2"/></svg>`
	body := map[string]any{"message_id": reply.ID.String(), "svg": svg}

	if items := e.want("GET", "/library?kind=diagram", nil, 200)["items"].([]any); len(items) != 0 {
		t.Fatalf("saved before asked: %v", items)
	}
	first := e.want("POST", "/library/diagrams", body, http.StatusCreated)
	again := e.want("POST", "/library/diagrams", body, http.StatusCreated)
	if first["id"] != again["id"] || first["kind"] != "diagram" || first["content_type"] != "image/svg+xml" {
		t.Fatalf("saves %v %v", first, again)
	}
	items := e.want("GET", "/library?kind=diagram", nil, 200)["items"].([]any)
	if len(items) != 1 || items[0].(map[string]any)["chat_id"] != chatID.String() {
		t.Fatalf("items %v", items)
	}
	if images := e.want("GET", "/library?kind=image", nil, 200)["items"].([]any); len(images) != 0 {
		t.Fatalf("diagram listed as an image: %v", images)
	}

	// An SVG never renders as a page on the app's origin.
	id := first["id"].(string)
	res, err := http.Get(e.srv.URL + "/api/v1/library/" + id + "/content")
	if err != nil {
		t.Fatal(err)
	}
	got, _ := io.ReadAll(res.Body)
	res.Body.Close()
	if string(got) != svg || res.Header.Get("Content-Security-Policy") != "sandbox" || !strings.HasPrefix(res.Header.Get("Content-Disposition"), "attachment") {
		t.Fatalf("content %q %v", got, res.Header)
	}

	// A diagram can't stand in for a likeness.
	e.want("PUT", "/library/"+id+"/reference", map[string]any{"role": "self"}, http.StatusUnprocessableEntity)

	for _, bad := range []string{"", "<div></div>", "not xml", `<svg viewBox="0 0 1 1"></svg>`, strings.Repeat(" ", 8) + "<svg" + strings.Repeat("x", runs.MaxLibraryDiagramBytes)} {
		e.want("POST", "/library/diagrams", map[string]any{"message_id": reply.ID.String(), "svg": bad}, http.StatusUnprocessableEntity)
	}
	mine, err := e.q.AppendChatMessage(ctx, store.AppendChatMessageParams{SessionID: chatID, Role: "user", BodyMd: "hi", ContextRefs: []byte("[]"), Citations: []byte("[]")})
	if err != nil {
		t.Fatal(err)
	}
	e.want("POST", "/library/diagrams", map[string]any{"message_id": mine.ID.String(), "svg": svg}, http.StatusUnprocessableEntity)
	e.want("POST", "/library/diagrams", map[string]any{"message_id": uuid.NewString(), "svg": svg}, http.StatusNotFound)

	// Removing it frees the object; it can be saved again.
	e.want("DELETE", "/library/"+id, nil, http.StatusNoContent)
	if keys := s3.keys(avatarBucket + "/library-diagrams/"); len(keys) != 0 {
		t.Fatalf("object kept %v", keys)
	}
	e.want("POST", "/library/diagrams", body, http.StatusCreated)
}
