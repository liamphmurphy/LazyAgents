package agentapi

import (
	"context"
	"fmt"

	"github.com/liamphmurphy/vesper/server/internal/agents"
	"github.com/liamphmurphy/vesper/server/internal/apperr"
	"github.com/liamphmurphy/vesper/server/internal/transcript"
)

// videoTranscripts fetches YouTube captions; tests point it at a fake.
var videoTranscripts = transcript.NewYouTube()

type VideoTranscriptIn struct {
	URL      string  `json:"url" jsonschema:"The YouTube link the person shared (watch, youtu.be, shorts, embed or live)"`
	Language string  `json:"language,omitempty" jsonschema:"Preferred caption language code, e.g. en (default) or es"`
	From     float64 `json:"from_seconds,omitempty" jsonschema:"Only lines from this many seconds in, e.g. where the person says they are"`
	To       float64 `json:"to_seconds,omitempty" jsonschema:"Only lines up to this many seconds in"`
}

// videoTranscript gives a chat the timestamped captions of a YouTube video, so
// it can watch along with the person.
func videoTranscript(ctx context.Context, d Deps, c agents.Caller, in VideoTranscriptIn) (any, error) {
	s, err := chatScopeFor(ctx, d, c)
	if err != nil {
		return nil, err
	}
	if s == nil {
		return nil, apperr.Conflict("get_video_transcript only works in a chat with a person")
	}
	if in.From < 0 || in.To < 0 || (in.To > 0 && in.To < in.From) {
		return nil, apperr.Invalid("to_seconds", "give a window with 0 ≤ from_seconds ≤ to_seconds")
	}
	id, err := transcript.VideoID(in.URL)
	if err != nil {
		return nil, err
	}
	t, err := videoTranscripts.Fetch(ctx, id, in.Language)
	if err != nil {
		return nil, err
	}
	text, cut, truncated := transcript.Render(t.Lines, in.From, in.To, transcript.DefaultMaxChars)
	out := map[string]any{
		"title": t.Title, "channel": t.Channel, "duration": transcript.Timestamp(float64(t.LengthSeconds)),
		"language": t.Language, "auto_generated": t.AutoGenerated, "transcript": text,
	}
	if len(t.Languages) > 0 {
		out["other_languages"] = t.Languages
	}
	if t.AutoGenerated {
		out["note"] = "Auto-generated captions: names and jokes may be misheard, and there are no speaker labels."
	}
	if truncated {
		out["truncated"] = fmt.Sprintf("Cut for length at %s; call again with from_seconds %d to read on.", transcript.Timestamp(cut), int(cut))
	}
	return out, nil
}
