func TestVideoID(t *testing.T) {
	for in, want := range map[string]string{
		"dQw4w9WgXcQ": "dQw4w9WgXcQ",
		"https://www.youtube.com/watch?v=dQw4w9WgXcQ&t=42s":   "dQw4w9WgXcQ",
		"youtube.com/watch?v=dQw4w9WgXcQ":                     "dQw4w9WgXcQ",
		"https://youtu.be/dQw4w9WgXcQ?si=abc":                 "dQw4w9WgXcQ",
		"https://m.youtube.com/shorts/dQw4w9WgXcQ":            "dQw4w9WgXcQ",
		"https://www.youtube-nocookie.com/embed/dQw4w9WgXcQ":  "dQw4w9WgXcQ",
		"https://www.youtube.com/live/dQw4w9WgXcQ?feature=sh": "dQw4w9WgXcQ",
	} {
		if got, err := VideoID(in); err != nil || got != want {
			t.Errorf("VideoID(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, in := range []string{"", "https://evil.example/watch?v=dQw4w9WgXcQ", "https://youtube.com.evil.example/watch?v=dQw4w9WgXcQ",
		"https://www.youtube.com/watch?v=short", "ftp://youtube.com/watch?v=dQw4w9WgXcQ", "https://www.youtube.com/@channel"} {
		if got, err := VideoID(in); err == nil {
			t.Errorf("VideoID(%q) = %q, want an error", in, got)
		}
	}
}

func TestParseTimedText(t *testing.T) {
	classic := `<?xml version="1.0" encoding="utf-8" ?><transcript><text start="0.5" dur="2.1">Truth or &amp;#39;Drink&amp;#39;</text>` +
		`<text start="3" dur="1">  <font color="#E5E5E5">no</font>   way </text><text start="4" dur="1"></text></transcript>`
	lines, err := parseTimedText([]byte(classic))
	if err != nil {
		t.Fatal(err)
	}
	if len(lines) != 2 || lines[0].Text != "Truth or 'Drink'" || lines[0].Start != 0.5 || lines[1].Text != "no way" {
		t.Fatalf("classic = %+v", lines)
	}
	srv3 := `<timedtext format="3"><body><p t="61500" d="1500"><s>hello</s><s> there</s></p><p t="63000" d="800">plain</p></body></timedtext>`
	if lines, err = parseTimedText([]byte(srv3)); err != nil {
		t.Fatal(err)
	}
	if len(lines) != 2 || lines[0].Text != "hello there" || lines[0].Start != 61.5 || lines[1].Text != "plain" {
		t.Fatalf("srv3 = %+v", lines)
	}
}

func TestRender(t *testing.T) {
	lines := []Line{{0, 2, "one"}, {65, 2, "two"}, {3700, 1, "three"}}
	if got, _, cut := Render(lines, 0, 0, 0); cut || got != "[0:00] one\n[1:05] two\n[1:01:40] three\n" {
		t.Fatalf("all = %q", got)
	}
	if got, _, _ := Render(lines, 60, 120, 0); got != "[1:05] two\n" {
		t.Fatalf("window = %q", got)
	}
	got, at, cut := Render(lines, 0, 0, 25)
	if !cut || at != 3700 || got != "[0:00] one\n[1:05] two\n" {
		t.Fatalf("capped = %q at %v cut %v", got, at, cut)
	}
}

func TestPickTrack(t *testing.T) {
	tracks := []captionTrack{{LanguageCode: "de"}, {LanguageCode: "en", Kind: "asr"}, {LanguageCode: "en-GB"}}
	if got := pickTrack(tracks, ""); got.LanguageCode != "en-GB" {
		t.Errorf("default = %+v, want uploaded English over auto-generated", got)
	}
	if got := pickTrack(tracks, "DE"); got.LanguageCode != "de" {
		t.Errorf("de = %+v", got)
	}
	if got := pickTrack([]captionTrack{{LanguageCode: "fr", Kind: "asr"}, {LanguageCode: "ja"}}, "en"); got.LanguageCode != "ja" {
		t.Errorf("fallback = %+v, want the uploaded track", got)
	}
}

func TestFetch(t *testing.T) {
	var player map[string]any
	var srv *httptest.Server
	srv = httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case "/watch":
			_, _ = io.WriteString(w, `<script>ytcfg.set({"INNERTUBE_API_KEY": "KEY_123"})</script>`)
		case "/youtubei/v1/player":
			if r.URL.Query().Get("key") != "KEY_123" {
				t.Errorf("player key = %q", r.URL.RawQuery)
			}
			_ = json.NewDecoder(r.Body).Decode(&player)
			// The track URL points elsewhere; only its path and query are used.
			_, _ = io.WriteString(w, `{"playabilityStatus":{"status":"OK"},"videoDetails":{"title":"Deathbed Roasts","author":"The OG Crew","lengthSeconds":"754"},
				"captions":{"playerCaptionsTracklistRenderer":{"captionTracks":[
				{"baseUrl":"https://elsewhere.example/api/timedtext?v=dQw4w9WgXcQ&lang=en&fmt=srv3","languageCode":"en","kind":"asr"},
				{"baseUrl":"https://elsewhere.example/api/timedtext?v=dQw4w9WgXcQ&lang=es","languageCode":"es"}]}}}`)
		case "/api/timedtext":
			if r.URL.Query().Get("fmt") != "" || r.URL.Query().Get("lang") != "en" {
				t.Errorf("track query = %q", r.URL.RawQuery)
			}
			_, _ = io.WriteString(w, `<transcript><text start="1" dur="2">you&amp;#39;re dead to me</text></transcript>`)
		default:
			http.NotFound(w, r)
		}
	}))
	defer srv.Close()
	y := &YouTube{HTTP: srv.Client(), BaseURL: srv.URL}
	got, err := y.Fetch(context.Background(), "dQw4w9WgXcQ", "")
	if err != nil {
		t.Fatal(err)
	}
	if got.Title != "Deathbed Roasts" || got.Channel != "The OG Crew" || got.LengthSeconds != 754 || got.Language != "en" || !got.AutoGenerated ||
		len(got.Languages) != 1 || got.Languages[0] != "es" || len(got.Lines) != 1 || got.Lines[0].Text != "you're dead to me" {
		t.Fatalf("got %+v", got)
	}
	if player["videoId"] != "dQw4w9WgXcQ" {
		t.Errorf("player body = %v", player)
	}
}

func TestFetchExplainsFailures(t *testing.T) {
	for name, body := range map[string]string{
		"no captions": `{"playabilityStatus":{"status":"OK"},"videoDetails":{"title":"x"}}`,
		"won't play":  `{"playabilityStatus":{"status":"LOGIN_REQUIRED","reason":"Sign in to confirm your age"}}`,
	} {
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			if r.URL.Path == "/youtubei/v1/player" {
				_, _ = io.WriteString(w, body)
			}
		}))
		_, err := (&YouTube{HTTP: srv.Client(), BaseURL: srv.URL}).Fetch(context.Background(), "dQw4w9WgXcQ", "")
		srv.Close()
		if err == nil || (name == "won't play" && !strings.Contains(err.Error(), "Sign in")) || (name == "no captions" && !strings.Contains(err.Error(), "no captions")) {
			t.Errorf("%s: err = %v", name, err)
		}
	}
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) { w.WriteHeader(http.StatusTooManyRequests) }))
	defer srv.Close()
	if _, err := (&YouTube{HTTP: srv.Client(), BaseURL: srv.URL}).Fetch(context.Background(), "dQw4w9WgXcQ", ""); err == nil || !strings.Contains(err.Error(), "rate limiting") {
		t.Errorf("429: err = %v", err)
	}
}
