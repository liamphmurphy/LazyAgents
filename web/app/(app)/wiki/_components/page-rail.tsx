export function PanelSection({ title, count, action, children, icon }: { title: string; count?: number; action?: ReactNode; children: ReactNode; icon?: "graph" }) {
  return (
    <section className="flex flex-col gap-2">
      <h2 className="flex items-center gap-1.5 text-[12.5px] text-fg-tertiary">
        {icon && <Icon name={icon} size={13} />}
        {title}
        {count !== undefined && count > 0 && <span className="font-mono">{count}</span>}
        {action && <span className="ml-auto">{action}</span>}
      </h2>
      {children}
    </section>
  );
}

const Empty = ({ children }: { children: ReactNode }) => <p className="text-xs text-fg-tertiary">{children}</p>;

function Rows() {
  return (
    <div aria-busy="true" className="flex flex-col gap-2">
      <Skeleton className="h-3 w-2/3" />
      <Skeleton className="h-3 w-1/2" />
    </div>
  );
}

/** Pattern index URL for a topic and/or tag (tag chips in the rail link here). */
export function patternIndexHref({ topic, tag }: { topic?: string; tag?: string }) {
  const q = new URLSearchParams({ index: "patterns" });
  if (topic) q.set("topic", topic);
  if (tag) q.set("tag", tag);
  return `/wiki?${q}`;
}

// ------------------------------------------------------------ tags

export function TagsSection({ topic, tags }: { topic: string; tags: string[] }) {
  return (
    <PanelSection title="Tags">
      {topic || tags.length ? (
        <div className="flex flex-wrap gap-1.5">
          {topic && (
            <Link
              href={patternIndexHref({ topic })}
              className="inline-flex h-[22px] items-center rounded-full bg-pill-human-bg px-2.5 text-[11.5px] text-pill-human-fg hover:underline"
              title={`Patterns in ${topic}`}
            >
              {topic}
            </Link>
          )}
          {tags.map((t) => (
            <Link
              key={t}
              href={patternIndexHref({ tag: t })}
              className="inline-flex h-[22px] items-center rounded-full border border-border px-2.5 font-mono text-[11px] text-fg-secondary hover:bg-hover hover:text-fg"
              title={`Patterns tagged #${t}`}
            >
              #{t}
            </Link>
          ))}
        </div>
      ) : (
        <Empty>
          No tags. Add a <code className="inline">Tags: a, b</code> line at the top of the page.
        </Empty>
      )}
    </PanelSection>
  );
}

// ------------------------------------------------------------ linked tickets

const STATUS_TONE: Record<TicketStatus, PillTone> = {
  backlog: "neutral",
  todo: "neutral",
  in_progress: "review",
  in_review: "human",
  done: "done",
  canceled: "neutral",
};

type TicketRow = { key: string; title: string; status?: string; how: string };

/** Tickets the page is attached to, plus tickets (and their comments) that [[link]] it. */
export function LinkedTickets({ page }: { page: Artifact }) {
  const back = useBacklinks("artifact", page.id);
  const rows = new Map<string, TicketRow>();
  for (const t of page.tickets) rows.set(t.key, { key: t.key, title: t.title, status: t.status, how: t.relation === "generated" ? "Generated by this ticket" : "Attached as context" });
  const linked = back.data?.linked ?? [];
  for (const kind of ["ticket", "comment"] as const) {
    for (const m of linked) {
      const s: LinkTarget = m.source;
      if (m.source_kind !== kind || !s.display_id || rows.has(s.display_id)) continue;
      rows.set(
        s.display_id,
        kind === "ticket"
          ? { key: s.display_id, title: s.title, status: s.status, how: "Links here" }
          : { key: s.display_id, title: "Mentioned in a comment", how: "A comment links here" },
      );
    }
  }
  const list = [...rows.values()];
  return (
    <PanelSection title="Linked tickets" count={list.length}>
      {!back.data && !back.isError && list.length === 0 ? (
        <Rows />
      ) : list.length ? (
        <ul className="flex flex-col gap-1">
          {list.map((t) => (
            <li key={t.key}>
              <Link href={`/tickets/${t.key}`} title={t.how} className="flex min-h-[26px] items-center gap-2 rounded-sm text-[13px] hover:bg-hover">
                <span className="flex-none font-mono text-[11.5px] text-fg-tertiary">{t.key}</span>
                <span className="min-w-0 flex-1 truncate">{t.title}</span>
                {t.status && t.status in STATUS_TONE && (
                  <SmallPill tone={STATUS_TONE[t.status as TicketStatus]}>{STATUS_LABEL[t.status as TicketStatus]}</SmallPill>
                )}
              </Link>
            </li>
          ))}
        </ul>
      ) : (
        <Empty>No tickets link here.</Empty>
      )}
      {back.isError && <Empty>Couldn&apos;t load tickets that link here.</Empty>}
    </PanelSection>
  );
}

// ------------------------------------------------------------ cited by

const reads = (n: number) => `${n} ${n === 1 ? "read" : "reads"}`;

/** Runs and chats that read the page (from recorded reads). Replaces "Read by". */
export function CitedBy({ id }: { id: string }) {
  const { data, isError } = useWikiCitations(id);
  const [all, setAll] = useState(false);
  const summary = data && (data.runs || data.chats) ? [data.runs && `${data.runs} ${data.runs === 1 ? "run" : "runs"}`, data.chats && `${data.chats} ${data.chats === 1 ? "chat" : "chats"}`].filter(Boolean).join(" · ") : "";
  const shown = all ? (data?.citations ?? []) : (data?.citations ?? []).slice(0, 4);
  const unlinkedReads = (data?.unlinked ?? []).reduce((n, r) => n + r.reads, 0);
  return (
    <section className="flex flex-col gap-2">
      <h2 className="text-[12.5px] text-fg-tertiary">
        Cited by {summary && <span className="text-fg-2">{summary}</span>}
      </h2>
      {isError ? (
        <Empty>Couldn&apos;t load citations.</Empty>
      ) : !data ? (
        <Rows />
      ) : (
        <>
          {data.citations.length > 0 && (
            <ul className="flex flex-col gap-1.5">
              {shown.map((c) => {
                const chat = c.purpose === "chat";
                return (
                  <li key={c.run_id} className="flex items-center gap-2 text-[12.5px]">
                    {chat ? (
                      <Icon name="msg" size={14} className="flex-none text-fg-secondary" />
                    ) : (
                      <AgentAvatar name={c.agent.name} colorIndex={c.agent.color_index} label={false} />
                    )}
                    <span className="min-w-0 flex-1 truncate">
                      {chat ? (
                        c.chat_id ? (
                          <>
                            Chat ·{" "}
                            <Link href={`/chat/${c.chat_id}`} className="text-accent hover:underline">
                              {c.chat_title || "Untitled chat"}
                            </Link>
                          </>
                        ) : (
                          // Chats are private: someone else's is counted, not shown.
                          <span className="text-fg-secondary">Chat · someone else&apos;s chat</span>
                        )
                      ) : (
                        <>
                          <Link href={`/runs/${c.run_id}`} className="font-mono text-[11.5px] text-accent hover:underline">
                            {c.ticket_key ?? (c.purpose === "planning" ? "Planning" : "Run")}
                          </Link>{" "}
                          <span className="text-fg-2">{c.agent.handle}</span>
                        </>
                      )}
                    </span>
                    <span className="flex-none text-[11.5px] text-fg-tertiary" title={`Last read ${absoluteTime(c.last_read_at)}`}>
                      {reads(c.reads)} · {timelineTime(c.last_read_at)}
                    </span>
                  </li>
                );
              })}
            </ul>
          )}
          {data.citations.length > 4 && (
            <button type="button" className="self-start text-xs text-accent hover:underline" onClick={() => setAll(!all)}>
              {all ? "Show fewer" : `Show all ${data.citations.length}`}
            </button>
          )}
          {data.citations.length === 0 && data.unlinked.length === 0 && <Empty>No run or chat has read this page yet.</Empty>}
          {data.unlinked.length > 0 &&
            (data.citations.length > 0 ? (
              <Empty>
                {unlinkedReads === 1 ? "1 earlier read isn't" : `${unlinkedReads} earlier reads aren't`} linked to a run.
              </Empty>
            ) : (
              <Empty>
                {data.unlinked.map((r, i) => (
                  <span key={r.agent.id}>
                    {i > 0 && "; "}
                    Read {r.reads === 1 ? "once" : `${r.reads} times`} by {r.agent.handle}
                  </span>
                ))}{" "}
                before reads were linked to runs.
              </Empty>
            ))}
        </>
      )}
    </section>
  );
}

// ------------------------------------------------------------ history

/** ?compare= URL for this page. */
export function compareHref(path: string, from: string, to: string) {
  return `${wikiHref(path)}?compare=${encodeURIComponent(from)}..${encodeURIComponent(to)}`;
}

/** Versions, newest first; each older one diffs against the next. */
export function History({ page }: { page: Artifact }) {
  const [all, setAll] = useState(false);
  const vs = page.versions;
  const path = page.path ?? "";
  const shown = all ? vs : vs.slice(0, 8);
  return (
    <PanelSection
      title="History"
      count={vs.length}
      action={
        vs.length > 1 ? (
          <Link href={compareHref(path, vs[1].label, vs[0].label)} className="text-xs text-accent hover:underline">
            Compare…
          </Link>
        ) : undefined
      }
    >
      <ol className="flex flex-col">
        {shown.map((v, i) => {
          const next = i > 0 ? vs[i - 1] : undefined;
          return (
            <li key={v.id} className={cx("group flex min-h-[26px] items-center gap-2 rounded-sm px-1.5 -mx-1.5 text-xs text-fg-secondary", next && "hover:bg-hover")}>
              <span className="flex-none font-mono text-fg-2">{v.label}</span>
              <span className="min-w-0 flex-1 truncate" title={v.note || undefined}>
                {v.created_by.name}
                {v.note && ` · ${v.note}`}
              </span>
              {i === 0 ? (
                <span className="flex-none rounded-full bg-hover px-1.5 text-[10.5px] text-fg-secondary">current</span>
              ) : (
                next && (
                  <Link
                    href={compareHref(path, v.label, next.label)}
                    className="flex-none rounded-[5px] bg-pill-human-bg px-1.5 text-[11px] text-pill-human-fg opacity-80 hover:underline group-hover:opacity-100 focus-visible:opacity-100"
                    aria-label={`Diff ${v.label} to ${next.label}`}
                  >
                    Diff → {next.label}
                  </Link>
                )
              )}
              <span className="flex-none text-fg-tertiary" title={absoluteTime(v.created_at)}>
                {timelineTime(v.created_at)}
              </span>
            </li>
          );
        })}
      </ol>
      {vs.length === 1 && <Empty>Only one version so far.</Empty>}
      {vs.length > 8 && (
        <button type="button" className="self-start text-xs text-accent hover:underline" onClick={() => setAll(!all)}>
          {all ? "Show fewer" : `Show all ${vs.length}`}
        </button>
      )}
    </PanelSection>
  );
}
