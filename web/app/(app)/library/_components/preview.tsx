"use client";

import Link from "next/link";
import { useState } from "react";
import { contentUrl, type Artifact } from "@/lib/api/client";
import { useArtifact } from "@/lib/api/hooks";
import { cx } from "@/lib/cx";
import { fileKind, formatBytes } from "@/lib/files";
import { shortAgo } from "@/lib/format";
import { Button, ButtonLink } from "@/components/ui/button";
import { Icon } from "@/components/ui/icon";
import { Skeleton } from "@/components/ui/primitives";
import { AgentAvatar } from "@/components/domain/avatars";
import { artifactTitle } from "@/components/domain/artifacts";
import { NewVersionDialog } from "@/components/domain/artifact-dialogs";
import { DocTypeTag } from "@/components/domain/labels";
import { printHref } from "@/components/domain/print-mode";
import { ReviewChip } from "@/components/domain/mockup";

/** Outline sections shown: H2s when the doc has a single H1 title, else top level. */
export function visibleOutline(a: Artifact) {
  const h1s = a.outline.filter((s) => s.level === 1).length;
  const level = h1s <= 1 && a.outline.some((s) => s.level === 2) ? 2 : 1;
  return a.outline.filter((s) => s.level === level);
}

/** Abstract page thumbnail (decorative); real images preview as themselves. */
function Thumbnail({ a }: { a: Artifact }) {
  const c = a.current_version.content;
  if (a.type === "mockup" || (c.kind === "file" && c.content_type.startsWith("image/"))) {
    return (
      // eslint-disable-next-line @next/next/no-img-element -- user uploads, served by the API
      <img
        src={contentUrl(a.id, a.current_version.id)}
        alt={`Preview of ${a.title}`}
        className="max-h-[200px] w-full rounded-xl border border-border bg-surface object-contain"
      />
    );
  }
  const sections = visibleOutline(a).slice(0, 3);
  return (
    <div aria-hidden className="flex h-[200px] flex-col gap-2.5 overflow-hidden rounded-xl border border-border bg-surface p-5">
      <span className="h-2.5 w-3/5 rounded-full bg-track" />
      <span className="h-1.5 w-2/5 rounded-full bg-track" />
      {(sections.length ? sections : [null, null]).map((_, i) => (
        <div key={i} className="mt-3 flex flex-col gap-1.5">
          <span className="h-1.5 w-1/3 rounded-full bg-accent/60" />
          <span className="h-1 w-11/12 rounded-full bg-track" />
          <span className="h-1 w-4/5 rounded-full bg-track" />
        </div>
      ))}
    </div>
  );
}

function Meta({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <div className="flex flex-col gap-0.5">
      <span className="text-12 text-fg-tertiary">{label}</span>
      <span className="text-13 text-fg">{children}</span>
    </div>
  );
}

export function ArtifactPreview({ id, onClose }: { id: string; onClose: () => void }) {
  const { data: a, isError } = useArtifact(id);
  const [versioning, setVersioning] = useState(false);

  if (isError) return <p className="p-5 text-13 text-pill-blocked-fg">Couldn&apos;t load this artifact.</p>;
  if (!a) {
    return (
      <div aria-busy="true" className="flex flex-col gap-4 p-5">
        <Skeleton className="h-[200px] rounded-xl" />
        <Skeleton className="h-5 w-3/4" />
        <Skeleton className="h-3 w-full" />
      </div>
    );
  }
  const c = a.current_version.content;
  const outline = visibleOutline(a);

  return (
    <div className="flex flex-col gap-5 p-5">
      <div className="flex items-center gap-1">
        <DocTypeTag type={a.type} />
        <Link href={`/artifacts/${a.id}`} aria-label="Open full view" title="Open full view" className="ml-auto grid size-7 place-items-center rounded-sm text-fg-secondary hover:bg-hover hover:text-fg">
          <Icon name="link" size={14} />
        </Link>
        <button type="button" aria-label="Close preview" onClick={onClose} className="grid size-7 place-items-center rounded-sm text-fg-secondary hover:bg-hover hover:text-fg">
          <Icon name="x" size={14} />
        </button>
      </div>
      <Thumbnail a={a} />
      <div className="flex flex-col gap-2">
        <h2 className="type-title">
          <Link href={`/artifacts/${a.id}`} className="hover:underline">
            {artifactTitle(a)}
          </Link>
        </h2>
        {a.summary && <p className="text-13 leading-relaxed text-fg-secondary">{a.summary}</p>}
      </div>
      <div className="grid grid-cols-2 gap-x-4 gap-y-3">
        <Meta label={a.author.type === "agent" ? "Generated by" : "Owner"}>{a.author.name}</Meta>
        <Meta label="Version">
          <span className="font-mono text-12">
            {a.current_version.label} · {shortAgo(a.current_version.created_at)}
          </span>
        </Meta>
        <Meta label={c.kind === "markdown" ? "Length" : "File"}>
          {c.kind === "markdown" ? `${a.outline.length} sections` : `${fileKind(c.content_type, c.filename)} · ${formatBytes(c.size_bytes)}`}
        </Meta>
        {a.current_version.review && (
          <Meta label="Review">
            <ReviewChip state={a.current_version.review.state} />
          </Meta>
        )}
        <Meta label="Epic">{a.epic ? <span className="text-accent">{a.epic.name}</span> : <span className="text-fg-tertiary">None</span>}</Meta>
      </div>

      {outline.length > 0 && (
        <section className="flex flex-col gap-1">
          <h3 className="text-13 text-fg-tertiary">Outline</h3>
          <ol>
            {outline.map((s, i) => (
              <li key={s.id}>
                <Link href={`/artifacts/${a.id}#${s.anchor}`} className="flex h-[26px] items-center gap-3 rounded-sm text-13 hover:bg-hover">
                  <span className="w-5 font-mono text-12 text-fg-tertiary">§{i + 1}</span>
                  <span className="flex-1 truncate">{s.heading}</span>
                  <span className={cx("font-mono text-12", s.citations ? "text-fg-secondary" : "text-fg-tertiary")} aria-label={`${s.citations} citations`}>
                    {s.citations}
                  </span>
                </Link>
              </li>
            ))}
          </ol>
          <p className="text-12 text-fg-tertiary">Right column: times agents cited each section</p>
        </section>
      )}

      <section className="flex flex-col gap-2">
        <h3 className="text-13 text-fg-tertiary">Read by</h3>
        {a.read_by.length ? (
          <div className="flex flex-wrap gap-1.5">
            {a.read_by.map((r) => (
              <span key={r.agent.id} title={`${r.reads} reads`} className="inline-flex h-[26px] items-center gap-1.5 rounded-sm border border-border-strong pl-1 pr-2 text-12">
                <AgentAvatar name={r.agent.name} colorIndex={r.agent.color_index} label={false} />
                {r.agent.name}
              </span>
            ))}
          </div>
        ) : (
          <p className="text-12 text-fg-tertiary">No agent has read this yet.</p>
        )}
      </section>

      {a.tickets.length > 0 && (
        <section className="flex flex-col gap-1">
          <h3 className="text-13 text-fg-tertiary">Tickets</h3>
          {a.tickets.slice(0, 6).map((t) => (
            <Link key={t.key} href={`/tickets/${t.key}`} className="flex h-7 items-center gap-2 rounded-sm text-13 hover:bg-hover">
              <span className="w-16 font-mono text-12 text-fg-tertiary">{t.key}</span>
              <span className="flex-1 truncate">{t.title}</span>
              {t.relation === "generated" && <span className="text-11 text-doc-report">generated</span>}
            </Link>
          ))}
          {a.tickets.length > 6 && <span className="text-12 text-fg-tertiary">and {a.tickets.length - 6} more</span>}
        </section>
      )}

      <div className="grid grid-cols-2 gap-2">
        {a.type === "mockup" && (
          <ButtonLink variant="primary" icon="edit" className="justify-center" href={`/artifacts/${a.id}?edit=1`}>
            Edit
          </ButtonLink>
        )}
        <Button variant="outline" className="justify-center" onClick={() => setVersioning(true)}>
          New version
        </Button>
        {c.kind === "markdown" && a.type !== "mockup" && (
          <ButtonLink variant="outline" icon="printer" className="justify-center" href={printHref(a.id)} target="_blank">
            Export PDF
          </ButtonLink>
        )}
        {(a.type === "prd" || a.type === "spec") && a.project && <ButtonLink variant="secondary" href={`/plans?artifact=${a.id}&project=${a.project.key}`}>
          Generate tickets
        </ButtonLink>}
      </div>
      {versioning && <NewVersionDialog artifact={a} open onOpenChange={setVersioning} />}
    </div>
  );
}
