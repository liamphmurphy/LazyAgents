import { useArtifacts } from "@/lib/api/hooks";
import { cx } from "@/lib/cx";
import { fileKind, formatBytes } from "@/lib/files";
import { Icon } from "@/components/ui/icon";
import { DocTypeTag } from "./labels";
import { ReviewChip } from "./mockup";
import { floatPanel } from "./pickers";
import { hoverReveal } from "@/lib/reveal";

/** "ADR-012 · Postgres declarative partitioning" for numbered types. */
export function artifactTitle(a: { title: string; display_id?: string }) {
  return a.display_id ? `${a.display_id} · ${a.title}` : a.title;
}

/** Second line in lists: "v3 · 9 sections", "Generated · 5 sections", "PNG · 17 KB". */
export function artifactMeta(a: ArtifactSummary) {
  const c = a.content;
  const what =
    c.kind === "file"
      ? `${fileKind(c.content_type, c.filename)} · ${formatBytes(c.size_bytes)}`
      : `${c.sections} ${c.sections === 1 ? "section" : "sections"}`;
  const version = a.type === "report" && a.author.type === "agent" ? "Generated" : a.version_label;
  return [version, what].filter(Boolean).join(" · ");
}

/**
 * Doc card (DESIGN.md §4): type tag and version, title, provenance line.
 * Reports read "Generated by <agent>"; context docs show whether the
 * ticket's agent has read them.
 */
export function DocCard({ doc, assignee, onRemove }: { doc: DocCardData; assignee?: string; onRemove?: () => void }) {
  const generated = doc.relation === "generated";
  return (
    <div className="group relative flex flex-col gap-2 rounded-lg border border-border bg-surface p-3 hover:border-border-hover">
      <div className="flex items-center justify-between gap-2">
        <span className="flex items-center gap-1.5">
          <DocTypeTag type={doc.type} />
          {doc.review_state && <ReviewChip state={doc.review_state} />}
        </span>
        <span className="font-mono text-[11px] text-fg-tertiary">{doc.display_id?.replace(/^ADR-/, "") ?? doc.version_label}</span>
      </div>
      <Link href={`/artifacts/${doc.id}`} className="font-medium leading-snug text-fg after:absolute after:inset-0">
        {doc.title}
      </Link>
      <span className={cx("flex items-center gap-1.5 text-xs", generated ? "text-doc-report" : "text-fg-tertiary")}>
        {generated ? (
          <>
            <Icon name="check" size={12} /> Generated by {doc.author.name}
          </>
        ) : doc.read_by_assignee && assignee ? (
          <>
            <Icon name="check" size={12} /> Read by {assignee}
          </>
        ) : assignee ? (
          <>Not read by {assignee} yet</>
        ) : (
          <>Added as context</>
        )}
      </span>
      {onRemove && (
        <button
          type="button"
          aria-label={`Remove ${doc.title} from this ticket`}
          onClick={onRemove}
          className={cx("absolute right-1.5 top-1.5 z-10 grid size-6 place-items-center rounded-sm bg-surface text-fg-tertiary hover:bg-hover hover:text-fg focus-visible:opacity-100", hoverReveal())}
        >
          <Icon name="x" size={12} />
        </button>
      )}
    </div>
  );
}

/** Searchable artifact picker popover, used to attach context to tickets. */
export function ArtifactPicker({
  onPick,
  exclude = [],
  project,
  children,
}: {
  onPick: (a: ArtifactSummary) => void;
  exclude?: string[];
  project?: string;
  children: ReactNode;
}) {
  const [open, setOpen] = useState(false);
  const [q, setQ] = useState("");
  const [active, setActive] = useState(0);
  const deferred = useDeferredValue(q.trim());
  const list = useArtifacts({ q: deferred || undefined, project });
  const options = (list.data?.artifacts ?? []).filter((a) => !exclude.includes(a.id)).slice(0, 30);

  function pick(i: number) {
    const a = options[i];
    if (!a) return;
    onPick(a);
    setOpen(false);
    setQ("");
    setActive(0);
  }

  return (
    <Popover.Root
      open={open}
      onOpenChange={(o) => {
        setOpen(o);
        if (!o) setQ("");
      }}
    >
      <Popover.Trigger asChild>{children}</Popover.Trigger>
      <Popover.Portal>
        <Popover.Content align="end" sideOffset={6} className={cx(floatPanel, "w-[360px] p-0")}>
          <div className="flex items-center gap-2 border-b border-border-subtle px-3">
            <Icon name="search" size={14} className="text-fg-tertiary" />
            <input
              autoFocus
              role="combobox"
              aria-expanded="true"
              aria-controls="artifact-options"
              aria-activedescendant={options.length ? `artifact-opt-${active}` : undefined}
              aria-label="Find an artifact"
              placeholder="Attach a PRD, spec, ADR…"
              value={q}
              onChange={(e) => {
                setQ(e.target.value);
                setActive(0);
              }}
              onKeyDown={(e) => {
                if (e.key === "ArrowDown") {
                  e.preventDefault();
                  setActive((i) => Math.min(i + 1, options.length - 1));
                }
                if (e.key === "ArrowUp") {
                  e.preventDefault();
                  setActive((i) => Math.max(i - 1, 0));
                }
                if (e.key === "Enter") {
                  e.preventDefault();
                  pick(active);
                }
              }}
              className="h-10 flex-1 bg-transparent text-[13px] outline-none placeholder:text-fg-tertiary"
            />
          </div>
          <div id="artifact-options" role="listbox" aria-label="Artifacts" className="max-h-[320px] overflow-y-auto p-1">
            {list.isPending && <div className="px-2 py-2 text-fg-tertiary">Loading…</div>}
            {!list.isPending && options.length === 0 && (
              <div className="px-2 py-2 text-fg-tertiary">{q ? `No artifacts match “${q}”` : "No artifacts to attach"}</div>
            )}
            {options.map((a, i) => (
              <div
                key={a.id}
                id={`artifact-opt-${i}`}
                role="option"
                aria-selected={i === active}
                onMouseEnter={() => setActive(i)}
                onClick={() => pick(i)}
                className={cx("flex h-10 cursor-default items-center gap-2.5 rounded-md px-2", i === active && "bg-hover")}
              >
                <DocTypeTag type={a.type} className="w-[52px] text-center" />
                <span className="flex min-w-0 flex-1 flex-col leading-tight">
                  <span className="truncate font-medium">{artifactTitle(a)}</span>
                  <span className="truncate text-[11.5px] text-fg-tertiary">
                    {a.project?.name ?? a.path ?? "Workspace"} · {artifactMeta(a)}
                  </span>
                </span>
              </div>
            ))}
          </div>
        </Popover.Content>
      </Popover.Portal>
    </Popover.Root>
  );
}
